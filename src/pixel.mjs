/**
 * Lay out text on the dot grid. Returns the lit pixels as {x, y, letter} in grid units plus the grid width.
 * One column between letters, three for a space.
 */
export function pixels(text) {
  let x = 0;
  const out = [];
  [...String(text).toUpperCase()].forEach((ch, li) => {
    if (ch === ' ') { x += 3; return; }
    const g = GLYPHS[ch];
    if (!g) throw new Error(`no glyph for "${ch}"`);
    g.forEach((row, y) => [...row].forEach((c, cx) => { if (c === '#') out.push({ x: x + cx, y, letter: li }); }));
    x += g[0].length + 1;
  });
  return { width: Math.max(0, x - 1), height: 7, pixels: out };
}

/**
 * The text as an SVG group. options: { x, y, size (one grid unit in px), dot (0..1 of a unit), cls, stagger (ms) }.
 * With `stagger`, every pixel carries a --d delay in a scattered order, for a print-in animation in CSS.
 */
export function pixelWord(text, { x = 0, y = 0, size = 4, dot = 0.84, cls = 'px', stagger = 0 } = {}) {
  const { width, pixels: px } = pixels(text);
  const s = (v) => +v.toFixed(2);
  const rects = px.map((p, n) => `<rect x="${s(x + p.x * size)}" y="${s(y + p.y * size)}" width="${s(size * dot)}" height="${s(size * dot)}"${stagger ? ` style="--d:${((n * 97) % 61) * stagger}ms"` : ''}/>`).join('');
  return { width: width * size, height: 7 * size, svg: `<g class="${cls}">${rects}</g>` };
}
